// Validates content/ and writes the browser bundles data/library.js and data/dict.js.
import fs from "node:fs";
import path from "node:path";
import { ROOT, loadAll, wordCount, lengthOf, LEVELS } from "./lib.mjs";

const { stories, articles, dict, errors } = loadAll();
if (errors.length) {
  console.error("Fix these errors first:\n" + errors.map((e) => " - " + e).join("\n"));
  process.exit(1);
}

const lowerKeys = (o) => Object.fromEntries(Object.entries(o || {}).map(([k, v]) => [k.toLowerCase().replace(/’/g, "'"), v]));
const library = [...stories, ...articles]
  .map((t) => {
    const words = wordCount(t.paragraphs);
    return { ...t, glossary: lowerKeys(t.glossary), words, length: lengthOf(words) };
  })
  .sort((a, b) => LEVELS.indexOf(a.level) - LEVELS.indexOf(b.level) || a.title.localeCompare(b.title));

const compactDict = Object.fromEntries(
  Object.keys(dict).sort().map((k) => [k, `${dict[k].pos}|${dict[k].tr}`])
);

const banner = "/* GENERATED by tools/build.mjs — edit content/ instead. */\n";
fs.mkdirSync(path.join(ROOT, "data"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "data/library.js"), banner + "window.LANTERN_LIBRARY = " + JSON.stringify(library) + ";\n");
fs.writeFileSync(path.join(ROOT, "data/dict.js"), banner + "window.LANTERN_DICT = " + JSON.stringify(compactDict) + ";\n");

const kb = (f) => (fs.statSync(path.join(ROOT, f)).size / 1024).toFixed(0) + " KB";
console.log(`library: ${stories.length} stories, ${articles.length} articles (${kb("data/library.js")})`);
console.log(`dict: ${Object.keys(compactDict).length} entries (${kb("data/dict.js")})`);
